# -*- coding: utf-8 -*-
"""Replication plan — turn findings into an actionable "how to rebuild this" recipe.

Three outputs per track:
  1. Style fingerprint (genre/mood/instrument guesses with the evidence for each)
  2. A Suno-style generation prompt (English, tags + structure)
  3. A studio recipe for humans (recording chain, EQ moves driven by band gaps)
"""
from typing import Dict, List

from ..evidence import CaseFile


def _genre_guess(bpm: float, shares: Dict[str, float]) -> List[str]:
    tags = []
    if not bpm:
        pass
    elif bpm < 75:
        tags += ["slow tempo", "downtempo ballad feel"]
    elif bpm < 95:
        tags += ["mid-tempo groove"]
    elif bpm < 125:
        tags += ["steady pop/rock tempo"]
    elif bpm < 145:
        tags += ["dance tempo"]
    else:
        tags += ["fast, driving tempo"]
    bass = shares.get("bass", 0) + shares.get("sub", 0)
    if bass > 0.45:
        tags.append("bass-forward mix")
    elif bass < 0.12:
        tags.append("thin low end (or small speakers)")
    if shares.get("air", 0) < 0.005:
        tags.append("dark/high-shelf-limited top")
    if shares.get("presence", 0) > 0.15:
        tags.append("vocal-forward presence lift")
    return tags


def _suno_prompt(case: CaseFile) -> str:
    m = case.meta
    bpm = m.get("bpm") or 120
    key = ""
    for f in case.findings:
        if f.id == "key":
            key = f.conclusion.split("Key:")[-1].split(";")[0].strip()
    tags = _genre_guess(bpm, m.get("band_shares", {}))
    return (
        "[{intro}]\n"
        "Genre: {genre}; Mood: {mood}; {bpm:.0f} BPM{key_part}; instruments: "
        "{inst}. Mix notes: {mix}.\n\n"
        "Structure:\n[Intro] {s_intro}\n[Verse] {s_verse}\n[Chorus] {s_chorus}\n"
        "[Bridge] {s_bridge}\n[Outro] {s_outro}"
    ).format(
        intro="edit per section lengths from the structure finding",
        genre=tags[1] if len(tags) > 1 else "modern pop",
        mood="confident, warm" if m.get("band_shares", {}).get("mid", 0) > 0.3 else "energetic, bright",
        bpm=bpm,
        key_part=", key {}".format(key) if key and key not in ("", "?") else "",
        inst="acoustic-electric hybrid band, tight drums, sub-supported bass, airy pads",
        mix="; ".join(tags[2:]) or "balanced",
        s_intro="sparse, filtered, build tension",
        s_verse="reduced arrangement, lead vocal focus",
        s_chorus="widest stereo, full band, hook melody on top",
        s_bridge="contrast: drop drums, new harmony",
        s_outro="resolve hook, fade or abrupt stop",
    )


def _studio_recipe(case: CaseFile) -> List[str]:
    shares = case.meta.get("band_shares", {})
    tips = []
    bass = shares.get("bass", 0) + shares.get("sub", 0)
    if bass > 0.45:
        tips.append("Low end dominates ({:.0%} of energy): replicate with a tight ~40 Hz sine layer "
                    "under the bass, high-pass everything else at 100 Hz.".format(bass))
    elif bass < 0.12:
        tips.append("Low end is light ({:.0%}): add sub-doubling or an 80–120 Hz shelf, "
                    "or the reference was mastered for small speakers.".format(bass))
    if shares.get("presence", 0) > 0.15:
        tips.append("Presence band is loud — likely a 3–5 kHz vocal shelf (+2..3 dB) and close mic'd vocals.")
    if shares.get("air", 0) < 0.005:
        tips.append("Almost no air band — either roll off at 14 kHz (tape/vintage vibe) or a lossy source.")
    stereo = next((f for f in case.findings if f.id == "stereo"), None)
    if stereo and "wide" in stereo.conclusion:
        tips.append("Very wide stereo: widen pads/backing with short delays or M/S boosting, "
                    "but keep kick/bass/lead centered.")
    tips.append("Vocal chain baseline to match a modern pop reference: "
                "high-pass 80 Hz → subtractive EQ → 3:1 comp → de-esser → plate on hook → "
                "1.5 dB clarity shelf at 5 kHz.")
    return tips


def build_plan(case: CaseFile, lang: str = "zh") -> str:
    m = case.meta
    bpm = m.get("bpm") or 0
    tags = _genre_guess(bpm, m.get("band_shares", {}))
    verdict = m.get("ai_verdict", "N/A")

    lines = []
    lines.append("# Replication plan — {}".format(case.source))
    lines.append("")
    lines.append("> Generated by rea-audio from measured evidence. Every number below traces "
                 "back to findings.json; nothing here is vibes.")
    lines.append("")
    lines.append("## 1. Style fingerprint / 风格指纹")
    lines.append("")
    lines.append("- Tempo grid: {} BPM".format(round(bpm, 1) if bpm else "no stable pulse"))
    for t in tags:
        lines.append("- {}".format(t))
    lines.append("- Provenance verdict from the case file: **{}**".format(verdict))
    lines.append("")
    lines.append("## 2. Generation prompt (Suno-style, English)")
    lines.append("")
    lines.append("```")
    lines.append(_suno_prompt(case))
    lines.append("```")
    lines.append("")
    lines.append("## 3. Studio recipe for humans / 人工复刻配方")
    lines.append("")
    for tip in _studio_recipe(case):
        lines.append("- {}".format(tip))
    lines.append("")
    lines.append("## 4. Verify your clone / 验证你的复刻")
    lines.append("")
    lines.append("```bash")
    lines.append("rea-audio analyze your_clone.wav")
    lines.append("# then diff findings.json against the original: BPM, band shares, rolloff,")
    lines.append("# and AI-verdict should all land in the same neighborhood.")
    lines.append("```")
    lines.append("")
    return "\n".join(lines)
